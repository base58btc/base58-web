"""Build/load a lossless index of the pinned store using the original pyln types.

The index is generated by Nix from the hash-verified store, never from student
input. Graph references are stored separately to avoid recursive pickling and
to recompute Python's process-specific node hashes when loading.
"""
import os
import pickle
import sys

from pyln.client import Gossmap, GossmapNodeId
from pyln.client.gossmap import GossmapNode, GossmapChannel, GossmapHalfchannel


def state_without(obj, *keys):
    return {key: value for key, value in vars(obj).items() if key not in keys}


def build_index(store, destination):
    graph = Gossmap(store)
    nodes = [(node.node_id.nodeid, state_without(node, "node_id", "channels", "_hash"))
             for node in graph.nodes.values()]
    channels = []
    for channel in graph.channels.values():
        halves = [state_without(hc, "channel", "source", "destination") if hc else None
                  for hc in channel.half_channels]
        channels.append((channel.node1.node_id.nodeid, channel.node2.node_id.nodeid,
                         state_without(channel, "node1", "node2", "half_channels"), halves))
    metadata = state_without(graph, "nodes", "channels", "store_file", "store_filename")
    metadata["processing_time"] = 0
    with open(destination, "wb") as output:
        pickle.dump((1, graph.store_file.tell(), metadata, nodes, channels), output, protocol=5)


def load_gossip():
    store = os.environ["LIGHTNING_GOSSIP_STORE"]
    index = os.environ.get("LIGHTNING_GOSSIP_INDEX")
    if not index:
        return Gossmap(store)
    # Only load the index supplied by the hash-verified Nix closure. Pickle is not
    # a format for untrusted uploads or arbitrary course workspace files.
    with open(index, "rb") as source:
        version, position, metadata, nodes, channels = pickle.load(source)
    if version != 1:
        raise ValueError("Unsupported gossip index")
    graph = Gossmap.__new__(Gossmap)
    graph.__dict__.update(metadata)
    graph.nodes, graph.channels = {}, {}
    graph.store_filename = store
    graph.store_file = open(store, "rb")
    graph.store_file.seek(position)
    for node_id, state in nodes:
        node = GossmapNode(GossmapNodeId(node_id))
        node.__dict__.update(state)
        graph.nodes[node.node_id] = node
    for node1, node2, state, halves in channels:
        channel = GossmapChannel.__new__(GossmapChannel)
        channel.__dict__ = state
        channel.node1 = graph.get_node(GossmapNodeId(node1))
        channel.node2 = graph.get_node(GossmapNodeId(node2))
        channel.half_channels = []
        for direction, half_state in enumerate(halves):
            hc = None
            if half_state is not None:
                hc = GossmapHalfchannel.__new__(GossmapHalfchannel)
                hc.__dict__ = half_state
                hc.channel = channel
                hc.source = channel.node1 if direction == 0 else channel.node2
                hc.destination = channel.node2 if direction == 0 else channel.node1
            channel.half_channels.append(hc)
        channel.node1.channels.append(channel)
        channel.node2.channels.append(channel)
        graph.channels[channel.scid] = channel
    return graph


if __name__ == "__main__":
    build_index(sys.argv[1], sys.argv[2])
