ALTER TABLE courses
  ADD COLUMN IF NOT EXISTS notion_id TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS difficulty TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS formats JSONB NOT NULL DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS topic TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS availability TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS popularity BIGINT NOT NULL DEFAULT 0 CHECK (popularity >= 0),
  ADD COLUMN IF NOT EXISTS price_usd BIGINT NOT NULL DEFAULT 0 CHECK (price_usd >= 0),
  ADD COLUMN IF NOT EXISTS flavor TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS long_description TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS prerequisites TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS featured BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS course_url TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS course_host TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS rating REAL NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS includes JSONB NOT NULL DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS chapters JSONB NOT NULL DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS catalog_imported_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS course_sessions (
  id TEXT NOT NULL,
  course_slug TEXT NOT NULL REFERENCES courses(slug),
  details JSONB NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id, course_slug)
);
CREATE INDEX IF NOT EXISTS course_sessions_course_idx ON course_sessions(course_slug);

-- Explicit, one-time catalog adjustments must not overwrite later admin edits.
CREATE TABLE IF NOT EXISTS course_catalog_updates (
  name TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
